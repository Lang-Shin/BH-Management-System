import { fireEvent, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it, vi } from 'vitest'
import { PrototypeContext } from '@/app/state/prototype-context'
import { createDemoData } from '@/data/fixtures/demo'
import Tenants from '@/features/tenants/tenants-page'
import { AddRoomDialog } from '@/features/rooms/add-room-dialog'
import { renderWithTheme as render } from './test-utils'

describe('preview form validation', () => {
  it('focuses the missing tenant name and validates optional contact details without saving', async () => {
    const user = userEvent.setup()
    const dispatch = vi.fn()
    const data = createDemoData()
    const before = JSON.stringify(data)
    render(<PrototypeContext.Provider value={{ data, dispatch, storageWarning: null }}><Tenants /></PrototypeContext.Provider>)
    await user.click(screen.getByRole('button', { name: 'Add tenant' }))
    const dialog = screen.getByRole('dialog', { name: 'Add a tenant' })
    const name = within(dialog).getByRole('textbox', { name: 'Full name' })
    expect(name).toBeRequired()
    expect(name).not.toHaveAttribute('aria-invalid', 'true')
    fireEvent.blur(name, { relatedTarget: within(dialog).getByRole('button', { name: 'Preview tenant' }) })
    expect(name).not.toHaveAttribute('aria-invalid', 'true')
    await user.click(within(dialog).getByRole('button', { name: 'Preview tenant' }))
    expect(name).toHaveFocus()
    expect(name).toHaveAttribute('aria-invalid', 'true')
    expect(name).toHaveAccessibleDescription(/Enter the tenant’s full name/)
    await user.type(name, 'Sample Resident')
    const email = within(dialog).getByLabelText('Email address (optional)')
    await user.type(email, 'invalid')
    await user.tab()
    expect(email).toHaveAccessibleDescription(/Enter an email address/)
    await user.click(within(dialog).getByRole('button', { name: 'Preview tenant' }))
    expect(email).toHaveFocus()
    await user.clear(email)
    const phone = within(dialog).getByLabelText('Phone number (optional)')
    await user.type(phone, 'letters')
    await user.click(within(dialog).getByRole('button', { name: 'Preview tenant' }))
    expect(phone).toHaveFocus()
    expect(phone).toHaveAccessibleDescription(/Enter 7–15 digits/)
    await user.clear(phone)
    await user.type(phone, '+63 912 345 6789')
    await user.click(within(dialog).getByRole('button', { name: 'Preview tenant' }))
    expect(screen.getByRole('dialog', { name: 'Tenant preview complete' })).toHaveTextContent('No new tenant was saved')
    expect(dispatch).not.toHaveBeenCalled()
    expect(JSON.stringify(data)).toBe(before)
  })

  it('rejects blank room names and invalid floor and bed counts, then resets on reopen', async () => {
    const user = userEvent.setup()
    render(<AddRoomDialog />)
    const trigger = screen.getByRole('button', { name: 'Add room' })
    await user.click(trigger)
    const dialog = screen.getByRole('dialog', { name: 'Add a room' })
    const name = within(dialog).getByLabelText('Room number or name')
    const floor = within(dialog).getByLabelText('Floor')
    const beds = within(dialog).getByLabelText('Number of beds')
    await user.type(name, '   ')
    fireEvent.change(floor, { target: { value: '-1' } })
    fireEvent.change(beds, { target: { value: '1.5' } })
    fireEvent.blur(name, { relatedTarget: within(dialog).getByRole('button', { name: 'Preview room' }) })
    expect(name).not.toHaveAttribute('aria-invalid', 'true')
    await user.click(within(dialog).getByRole('button', { name: 'Preview room' }))
    expect(name).toHaveFocus()
    expect(floor).toHaveAccessibleDescription(/whole floor number, 0 or higher/)
    expect(beds).toHaveAccessibleDescription(/whole number of beds, 1 or higher/)
    await user.clear(name)
    await user.type(name, '116')
    fireEvent.change(floor, { target: { value: '0' } })
    fireEvent.change(beds, { target: { value: '1' } })
    await user.click(within(dialog).getByRole('button', { name: 'Preview room' }))
    expect(screen.getByRole('dialog', { name: 'Room preview complete' })).toHaveTextContent('No new room was saved')
    await user.click(screen.getByRole('button', { name: 'Got it' }))
    await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
    await user.click(trigger)
    expect(screen.getByLabelText('Room number or name')).toHaveValue('')
    expect(screen.queryByRole('alert')).not.toBeInTheDocument()
  })

  it.each([null, 'Browser storage is unavailable.'])('disables unchanged notes and reports workspace updates with storage warning %s', async storageWarning => {
    const user = userEvent.setup()
    const dispatch = vi.fn()
    render(<PrototypeContext.Provider value={{ data: createDemoData(), dispatch, storageWarning }}><Tenants /></PrototypeContext.Provider>)
    await user.click(screen.getByRole('button', { name: 'View Alex Rivera' }))
    const save = screen.getByRole('button', { name: 'Save note' })
    expect(save).toBeDisabled()
    await user.type(screen.getByLabelText('Notes'), 'Sample reminder')
    expect(save).toBeEnabled()
    await user.click(save)
    expect(dispatch).toHaveBeenCalledWith(expect.objectContaining({ type: 'tenant/noteUpdated', notes: 'Sample reminder' }))
    const status = screen.getByText(/Note updated in this workspace/)
    expect(status).toHaveAttribute('role', 'status')
    if (storageWarning) expect(status).toHaveTextContent('Browser saving could not be confirmed')
    else expect(status).not.toHaveTextContent('Browser saving could not be confirmed')
  })
})
